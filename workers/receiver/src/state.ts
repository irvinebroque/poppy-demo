import { DurableObject } from 'cloudflare:workers';
import { fail, id, now, randomSecret, ProtocolError, type RpcResult, type Message, type Event, type TokenResponse } from '../../../shared/protocol';

type Session = { id: string; expires: number; account?: string; grant?: string; everAccount?: string; scope: string[] };
type Access = { session: string; expires: number; jkt: string; account?: string; grant?: string; scope: string[]; resource?: string };
type Grant = { account: string; scope: string[]; expires: number; revoked?: boolean };
type Conversation = { id: string; account?: string; parent?: string; direct?: string; status: 'working' | 'idle' | 'queued' | 'closed'; responder: 'agent' | 'human'; events: Event[]; context: Record<string, unknown> };
type State = { client: string; user: string; sessions: Record<string, Session>; access: Record<string, Access>; grants: Record<string, Grant>; conversations: Record<string, Conversation>; messages: Record<string, { content: string; result: RpcResult }>; exchanged: boolean };
export type Auth = { client: string; user: string; session: string; account?: string; scope: string[] };
export type Input = { client: string; user?: string; session?: string; jkt?: string; secret?: string; token?: string; grant?: string; scope?: string[]; resource?: string; conversation?: string; parent?: string; message?: Message; cursor?: string; wait?: boolean; account?: string; replacement?: string; requestId?: string };

export type StoredCode = { client?: string; redirect?: string; state?: string | null; challenge?: string; scope?: string[]; expires?: number; owner?: string };

export class ReplayGuard extends DurableObject<ReceiverEnv> {
  constructor(ctx: DurableObjectState, env: ReceiverEnv) { super(ctx, env); this.ctx.storage.sql.exec('CREATE TABLE IF NOT EXISTS replay (id TEXT PRIMARY KEY, expires INTEGER NOT NULL)'); }
  accept(key: string, expires: number): boolean {
    return this.ctx.storage.transactionSync(() => {
      this.ctx.storage.sql.exec('DELETE FROM replay WHERE expires < ?', now());
      const result = this.ctx.storage.sql.exec('INSERT OR IGNORE INTO replay (id, expires) VALUES (?, ?) RETURNING id', key, expires).toArray();
      return result.length === 1;
    });
  }
  saveCode(code: string, details: StoredCode) { this.ctx.storage.kv.put('code:' + code, details); }
  peekCode(code: string): StoredCode | undefined { return this.ctx.storage.kv.get<StoredCode>('code:' + code); }
  takeCode(code: string): StoredCode | undefined {
    return this.ctx.storage.transactionSync(() => { const value = this.ctx.storage.kv.get<StoredCode>('code:' + code); this.ctx.storage.kv.delete('code:' + code); return value; });
  }
}

export class CompanyUser extends DurableObject<ReceiverEnv> {
  dispatch(action: string, input: Input): string { return JSON.stringify(this.dispatchState(action, input)); }
  private dispatchState(action: string, input: Input): RpcResult {
    try {
      return this.ctx.storage.transactionSync(() => {
        let state = this.ctx.storage.kv.get<State>('state');
        if (!state) {
          if (action !== 'start' || !input.user) fail(['sign-in','refresh'].includes(action) ? 'invalid_grant' : 'invalid_token', 401);
          state = { client: input.client, user: input.user, sessions: {}, access: {}, grants: {}, conversations: {}, messages: {}, exchanged: false };
        }
        if (state.client !== input.client || (input.user && state.user !== input.user)) fail('invalid_session');
        // Bound transient state; conversations and their idempotency records intentionally survive sessions.
        for (const [key, value] of Object.entries(state.access)) if (value.expires < now()) delete state.access[key];
        const result = this.perform(state, action, input);
        this.ctx.storage.kv.put('state', state);
        return result;
      });
    } catch (error) {
      if (error instanceof ProtocolError) return { status: error.status, body: { error: error.code, ...error.extra } };
      throw error;
    }
  }
  private session(state: State, value?: string) {
    const s = value ? state.sessions[value] : undefined;
    if (!s || s.expires < now()) fail('invalid_session'); return s;
  }
  private issue(state: State, session: Session, input: Input, refresh?: string): RpcResult {
    const scope = input.scope ?? session.scope;
    if (scope.some(s => !session.scope.includes(s))) fail('invalid_scope');
    if (!input.jkt || !input.secret) fail('invalid_dpop_proof');
    state.access[input.secret] = { session: session.id, expires: now() + 3600, jkt: input.jkt, account: session.account, grant: session.grant, scope, resource: input.resource };
    // The random credential is generated by the Worker and only its hash is persisted here.
    const body: TokenResponse = { access_token: input.token!, token_type: 'DPoP', expires_in: 3600, session_id: session.id, signed_in: !!session.account, scope: scope.join(' '), ...(refresh ? { refresh_token: refresh, refresh_token_expires_in: 30 * 86400 } : {}) };
    return { status: 200, body: { ...body } };
  }
  private authenticate(state: State, input: Input): Auth {
    const t = state.access[input.secret ?? ''];
    if (!t || t.expires < now()) fail('invalid_token', 401);
    const session = this.session(state, t.session);
    if (t.jkt !== input.jkt) fail('invalid_dpop_proof', 401);
    if (t.resource && input.resource !== t.resource) fail('invalid_token', 401);
    // Check revocation at every request, including old signed-in Session Tokens.
    const signedIn = t.account && session.account === t.account && t.grant === session.grant && t.grant && !state.grants[t.grant]?.revoked && state.grants[t.grant]?.expires > now();
    return { client: state.client, user: state.user, session: session.id, account: signedIn ? t.account : undefined, scope: signedIn ? t.scope.filter(s => session.scope.includes(s)) : [] };
  }
  private require(auth: Auth, required: string[]) {
    if (!auth.account) fail('sign_in_required', 403);
    if (required.some(s => !auth.scope.includes(s))) fail('insufficient_scope', 403, { scope: required.join(' ') });
  }
  private event(c: Conversation, fields: Record<string, unknown>) { c.events.push({ id: id('evt_'), created_at: new Date().toISOString(), ...fields } as Event); }
  private stateEvent(c: Conversation, status: Conversation['status'], responder = c.responder) {
    if (c.status !== status || c.responder !== responder) { c.status = status; c.responder = responder; this.event(c, { type: 'state', status, responder }); }
  }
  private read(c: Conversation, cursor?: string): Record<string, unknown> {
    const index = cursor ? c.events.findIndex(e => e.id === cursor) : -1;
    if (cursor && index < 0) fail('invalid_cursor');
    const events = c.events.slice(index + 1, index + 101);
    return { conversation_id: c.id, events, cursor: events.at(-1)?.id ?? cursor ?? '', has_more: index + 1 + events.length < c.events.length, status: c.status, responder: c.responder };
  }
  private getConversation(state: State, auth: Auth, value?: string) {
    const c = state.conversations[value ?? '']; if (!c) fail('conversation_not_found', 404);
    if (c.account && !auth.account) fail('sign_in_required', 403);
    if (c.account && auth.account !== c.account) fail('conversation_not_found', 404);
    return c;
  }
  private reply(state: State, c: Conversation, auth: Auth, message: Message) {
    c.context = { ...c.context, ...message.context };
    this.event(c, { type: 'message', message: { ...message, role: 'user' } });
    this.stateEvent(c, 'working');
    const text = (message.text ?? '').toLowerCase(); let reply: string; let data: Record<string, unknown> | undefined;
    if (/order|return|exchange/.test(text)) {
      const required = /exchange|return/.test(text) ? ['poppy:read', 'poppy:write'] : ['poppy:read'];
      if (!auth.account || required.some(s => !auth.scope.includes(s))) {
        this.event(c, { type: 'authorization', error: auth.account ? 'insufficient_scope' : 'sign_in_required', ...(auth.account ? { scope: required.join(' ') } : {}) });
        reply = 'Please sign in and approve access so I can help with order #1042. Your conversation will stay open.';
      } else {
        c.account = auth.account;
        reply = state.exchanged ? 'The exchange is confirmed. Your insulated Stormline jacket in medium will ship in 2–3 business days.' : 'Order #1042 contains a Stormline shell in medium. The insulated version is available for $70 more. Review the exchange in your agent before confirming.';
        data = state.exchanged ? { exchange_id: 'exc_demo_1042', status: 'confirmed' } : { order_id: 'ord_1042', replacement_sku: 'stormline-insulated-m', price_difference: 70 };
      }
    } else if (c.responder === 'human') {
      reply = 'This demo has no staffed support desk. The automated store assistant can continue helping here.';
    } else {
      reply = message.sender === 'human' ? 'Hi! The Stormline insulated jacket is warmer than the shell and comes in medium. I can help look up your order once you approve access.' : 'Stormline shell: waterproof, uninsulated, $180. Stormline insulated: waterproof, warm lining, $250. Medium is in stock. Account access is required for orders and exchanges.';
      data = { products: [{ sku: 'stormline-shell-m', price: 180 }, { sku: 'stormline-insulated-m', price: 250 }] };
    }
    this.event(c, { type: 'message', message: { id: id('msg_'), role: 'company', sender: c.responder, text: reply, ...(data ? { data } : {}) } });
    this.stateEvent(c, 'idle');
  }
  private perform(state: State, action: string, input: Input): RpcResult {
    if (action === 'start') {
      let session: Session;
      if (input.session) { session = this.session(state, input.session); if (session.account) fail('invalid_grant'); }
      else { session = { id: id('ses_'), expires: now() + 86400, scope: [] }; state.sessions[session.id] = session; }
      return this.issue(state, session, input);
    }
    if (action === 'sign-in' || action === 'refresh') {
      let session: Session;
      if (input.session) session = this.session(state, input.session);
      else if (action === 'refresh') { session = { id: id('ses_'), expires: now() + 86400, scope: [] }; state.sessions[session.id] = session; }
      else fail('invalid_session');
      const grant = action === 'refresh' ? state.grants[input.grant ?? ''] : { account: 'demo-account', scope: input.scope ?? [], expires: now() + 30 * 86400 };
      if (!grant || grant.revoked || grant.expires < now()) fail('invalid_grant');
      if (session.everAccount && session.everAccount !== grant.account) fail('account_mismatch');
      if (input.scope?.some(s => !grant.scope.includes(s))) fail('invalid_scope');
      if (action === 'sign-in') state.grants[input.grant!] = grant;
      session.account = session.everAccount = grant.account; session.grant = input.grant; session.scope = grant.scope;
      return this.issue(state, session, input, action === 'sign-in' ? input.replacement : undefined);
    }
    if (action === 'revoke') {
      const g = state.grants[input.grant ?? ''];
      if (g) { g.revoked = true; for (const session of Object.values(state.sessions)) if (session.grant === input.grant) { delete session.account; delete session.grant; session.scope = []; } }
      return { status: 200, body: {} };
    }
    const auth = this.authenticate(state, input);
    if (action === 'authenticate') return { status: 200, body: { ...auth } };
    if (action === 'orders') { this.require(auth, ['poppy:read']); return { status: 200, body: { orders: [{ id: 'ord_1042', number: 1042, item: 'Stormline shell', size: 'M', price: 180, status: state.exchanged ? 'exchange_confirmed' : 'delivered' }] } }; }
    if (action === 'exchange') {
      this.require(auth, ['poppy:write']); if (input.replacement !== 'stormline-insulated-m') fail('invalid_replacement');
      state.exchanged = true; return { status: 201, body: { exchange_id: 'exc_demo_1042', order_id: 'ord_1042', replacement_sku: input.replacement, price_difference: 70, status: 'confirmed' } };
    }
    if (action === 'create' || action === 'message') {
      const m = input.message!;
      const content = JSON.stringify({ message: m, parent: input.parent ?? null, conversation: action === 'message' ? input.conversation : null });
      const old = state.messages[m.id]; if (old) { if (old.content !== content) fail('message_id_conflict', 409); return old.result; }
      let c: Conversation;
      if (action === 'create') {
        if (input.parent) { const parent = this.getConversation(state, auth, input.parent); if (parent.status === 'closed') fail('conversation_closed', 409); if (parent.parent) fail('conversation_not_found', 404); if (parent.direct) fail('direct_conversation_open', 409, { conversation_id: parent.direct }); if (m.sender !== 'human') fail('invalid_request'); }
        c = { id: id('cnv_'), status: 'idle', responder: 'agent', events: [], context: {}, parent: input.parent }; state.conversations[c.id] = c;
        if (input.parent) { const p = state.conversations[input.parent]; p.direct = c.id; c.account = p.account; this.event(p, { type: 'direct_opened', conversation_id: c.id }); }
      } else { c = this.getConversation(state, auth, input.conversation); if (c.status === 'closed') fail('conversation_closed', 409); if (c.direct) fail('direct_conversation_open', 409, { conversation_id: c.direct }); if (c.parent && m.sender !== 'human') fail('invalid_request'); }
      if (input.cursor && !c.events.some(e => e.id === input.cursor)) fail('invalid_cursor');
      this.reply(state, c, auth, m);
      const result = { status: action === 'create' ? 201 : 202, body: input.wait ? this.read(c, input.cursor) : { conversation_id: c.id, status: c.status, responder: c.responder } };
      state.messages[m.id] = { content, result }; return result;
    }
    const c = this.getConversation(state, auth, input.conversation);
    if (action === 'events') return { status: 200, body: this.read(c, input.cursor) };
    if (action === 'handoff') {
      if (c.status === 'closed') fail('conversation_closed', 409); if (c.direct) fail('direct_conversation_open', 409, { conversation_id: c.direct });
      this.stateEvent(c, 'queued');
      // No invented human: the next event read resolves this demo's unavailable handoff.
      this.event(c, { type: 'message', message: { id: id('msg_'), role: 'company', sender: 'agent', text: 'There is no staffed support desk in this demo. I can continue helping as the automated assistant.' } });
      this.stateEvent(c, 'idle'); return { status: 202, body: { conversation_id: c.id, status: c.status, responder: c.responder } };
    }
    if (action === 'close') {
      this.stateEvent(c, 'closed');
      if (c.direct) { this.stateEvent(state.conversations[c.direct], 'closed'); this.event(c, { type: 'direct_closed', conversation_id: c.direct }); delete c.direct; }
      if (c.parent) { const p = state.conversations[c.parent]; if (p.direct === c.id) { delete p.direct; this.event(p, { type: 'direct_closed', conversation_id: c.id }); } }
      return { status: 200, body: { conversation_id: c.id, status: c.status, responder: c.responder } };
    }
    fail('not_found', 404);
  }
}
